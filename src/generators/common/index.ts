function renderReadme(spec: HarnessSpec, opts: GenerateOptions): string {
  const g = spec.guardrails;
  const out: string[] = [];
  out.push(`# ${oneLine(spec.displayName)}`, "", spec.description.trim(), "");
  out.push("**Goal:** " + oneLine(spec.goal), "");
  out.push(
    "> Generated by `decree-harness` " +
      inlineCode(opts.decreeVersion) +
      ". `decree.json` at the project root is the source of truth: edit it (or run `npx decree-harness refine`) and regenerate with `npx decree-harness generate`. Do not hand-edit generated files you want to keep in sync.",
    "",
  );

  out.push("## Model", "");
  out.push(
    renderTable(
      ["Setting", "Value"],
      [
        ["Model", inlineCode(spec.model.id)],
        ["Effort", spec.model.effort],
        ["Thinking", spec.model.thinking],
        ["Subagent model", inlineCode(spec.model.subagentId)],
      ],
    ),
    "",
  );

  out.push("## Tools", "");
  if (spec.tools.length === 0) out.push("_No tools._", "");
  else {
    out.push(
      renderTable(
        ["Name", "Kind", "Read-only", "Approval", "Source"],
        spec.tools.map((t) => [
          inlineCode(t.name),
          t.kind,
          yesNo(t.readOnly),
          needsApproval(t, g.approvalMode) ? "required" : "no",
          t.source ?? "",
        ]),
      ),
      "",
    );
  }

  out.push("## Subagents", "");
  if (spec.subagents.length === 0) out.push("_None._", "");
  else {
    out.push(
      renderTable(
        ["Name", "When to delegate", "Tools", "Model"],
        spec.subagents.map((s) => [
          inlineCode(s.name),
          oneLine(s.description),
          s.tools.map((n) => inlineCode(n)).join(", "),
          inlineCode(subagentModel(spec, s.model)),
        ]),
      ),
      "",
    );
  }

  out.push("## Guardrails", "");
  out.push(
    `- Approval mode: **${g.approvalMode}**`,
    `- Max turns: ${g.maxTurns}; max output tokens per turn: ${g.maxOutputTokensPerTurn}` +
      (g.maxCostUsd !== undefined ? `; cost cap: $${g.maxCostUsd}` : ""),
    `- Blocked commands: ${g.blockedCommands.length ? g.blockedCommands.map((c) => inlineCode(c)).join(", ") : "none"}`,
    `- Allowed paths: ${g.allowedPaths.length ? g.allowedPaths.map((c) => inlineCode(c)).join(", ") : "none"}`,
    `- Redacted env vars: ${g.redactEnv.length ? g.redactEnv.map((c) => inlineCode(c)).join(", ") : "none"}`,
    "",
  );

  out.push("## Evals", "");
  if (spec.evals.length === 0) out.push("_No eval cases._", "");
  else {
    out.push(
      `${spec.evals.length} case(s) in \`evals.json\`. Run them with \`npx decree-harness eval\`.`,
      "",
      renderTable(
        ["Id", "Input", "Checks"],
        spec.evals.map((e) => [inlineCode(e.id), oneLine(e.input), summarizeExpect(e.expect)]),
      ),
      "",
    );
  }

  out.push("## Generated targets", "");
  const targets = orderedTargets(spec);
  if (targets.length === 0) out.push("_No targets selected._", "");
  for (const t of targets) {
    const r = targetRun(t, spec, opts);
    out.push(`- **${r.label}** (\`${r.dir}/\`): ${inlineCode(r.cmd)}${r.note ? ` (${r.note})` : ""}`);
  }
  if (targets.length) out.push("");
  out.push(
    "Environment: copy `.env.example` to `.env` and fill in the values.",
    "",
    "## Files",
    "",
    "- `harness.md`: full design doc of this harness (system prompt, every tool, guardrails). Review this in PRs.",
    "- `evals.json`: eval cases consumed by the generated eval runners.",
    "- `.env.example`: environment variables the harness reads.",
    "",
    "## Regenerate",
    "",
    codeBlock("npx decree-harness generate", "sh"),
    "",
  );
  return out.join("\n");
}

function summarizeExpect(e: HarnessSpec["evals"][number]["expect"]): string {
  const parts: string[] = [];
  if (e.toolsCalled?.length) parts.push(`calls ${e.toolsCalled.join(", ")}`);
  if (e.toolsNotCalled?.length) parts.push(`never calls ${e.toolsNotCalled.join(", ")}`);
  if (e.contains?.length) parts.push(`contains ${e.contains.map((s) => JSON.stringify(s)).join(", ")}`);
  if (e.notContains?.length) parts.push(`omits ${e.notContains.map((s) => JSON.stringify(s)).join(", ")}`);
  if (e.rubric) parts.push(`rubric: ${oneLine(e.rubric)}`);
  return parts.join("; ");
}

