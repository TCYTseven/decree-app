function renderTool(spec: HarnessSpec, t: ToolSpec): string {
  const out: string[] = [`### ${inlineCode(t.name)}`, "", demoteHeadings(t.description.trim(), 3) || "_No description._", ""];
  out.push(
    renderTable(
      ["Property", "Value"],
      [
        ["Kind", t.kind],
        ["Binding", inlineCode(describeBinding(t))],
        ["Read-only", yesNo(t.readOnly)],
        ["Destructive", yesNo(t.destructive)],
        ["Requires approval (flag)", yesNo(t.requiresApproval)],
        [`Asks for approval (mode: ${spec.guardrails.approvalMode})`, yesNo(needsApproval(t, spec.guardrails.approvalMode))],
        ["Source", t.source ?? ""],
      ],
    ),
    "",
  );
  if (t.http) {
    const h = t.http;
    const lines = [
      `- Method / path: ${inlineCode(`${h.method} ${h.path}`)}`,
      `- Base URL: ${inlineCode(`$${h.baseUrlEnv}`)}${h.defaultBaseUrl ? ` (default ${inlineCode(h.defaultBaseUrl)})` : ""}`,
    ];
    if (h.queryParams?.length) lines.push(`- Query params: ${h.queryParams.map((p) => inlineCode(p)).join(", ")}`);
    if (h.headerParams?.length) lines.push(`- Header params: ${h.headerParams.map((p) => inlineCode(p)).join(", ")}`);
    if (h.bodyParam) lines.push(`- Body param: ${inlineCode(h.bodyParam)}`);
    if (h.auth && h.auth.type !== "none") {
      lines.push(
        `- Auth: ${h.auth.type}${h.auth.env ? ` from ${inlineCode(`$${h.auth.env}`)}` : ""}${h.auth.type === "header" && h.auth.header ? ` in header ${inlineCode(h.auth.header)}` : ""}`,
      );
    }
    out.push(...lines, "");
  }
  if (t.shell) {
    out.push(codeBlock(displayShellCommand(t.shell.command), "sh"), "");
    const extras: string[] = [];
    if (t.shell.cwd && t.shell.cwd !== ".") extras.push(`- cwd: ${inlineCode(t.shell.cwd)}`);
    extras.push(`- Timeout: ${t.shell.timeoutMs ?? 120000} ms`);
    out.push(...extras, "");
  }
  if (t.fs) {
    out.push(`- Root: ${inlineCode(t.fs.root)}${t.fs.maxBytes ? `; max bytes: ${t.fs.maxBytes}` : ""}`, "");
  }
  if (t.inputSchema && Object.keys(t.inputSchema).length > 0) {
    out.push("Input schema:", "", codeBlock(JSON.stringify(t.inputSchema, null, 2), "json"), "");
  } else {
    out.push("_Server/built-in tool: no custom input schema._", "");
  }
  return out.join("\n");
}

function renderHarnessDoc(spec: HarnessSpec, opts: GenerateOptions): string {
  const g = spec.guardrails;
  const c = spec.context;
  const out: string[] = [];
  out.push(`# ${oneLine(spec.displayName)}: harness design`, "");
  out.push(
    `Name: ${inlineCode(spec.name)} · generator: ${spec.provenance.generator} · decree ${inlineCode(spec.provenance.decreeVersion)} (rendered by ${inlineCode(opts.decreeVersion)}) · created ${spec.provenance.createdAt} · profile ${inlineCode(spec.provenance.profileName)}`,
    "",
  );
  out.push(spec.description.trim(), "", "## Goal", "", blockquote(spec.goal.trim()), "");

  out.push("## Model", "");
  out.push(
    renderTable(
      ["Setting", "Value"],
      [
        ["Model", inlineCode(spec.model.id)],
        ["Effort", spec.model.effort],
        ["Thinking", spec.model.thinking],
        ["Subagent model", inlineCode(spec.model.subagentId)],
      ],
    ),
    "",
  );

  out.push("## System prompt", "", codeBlock(spec.systemPrompt, "markdown"), "");

  out.push(`## Tools (${spec.tools.length})`, "");
  if (spec.tools.length === 0) out.push("_No tools._", "");
  for (const t of spec.tools) out.push(renderTool(spec, t));

  out.push(`## Subagents (${spec.subagents.length})`, "");
  if (spec.subagents.length === 0) out.push("_None. The main agent does all the work._", "");
  for (const s of spec.subagents) {
    out.push(
      `### ${inlineCode(s.name)}`,
      "",
      demoteHeadings(s.description.trim(), 3),
      "",
      `- Exposed to the main agent as ${inlineCode(`delegate_to_${s.name.replace(/-/g, "_")}`)}`,
      `- Model: ${inlineCode(subagentModel(spec, s.model))}; effort: ${s.effort ?? "medium"}`,
      `- Tools: ${s.tools.length ? s.tools.map((n) => inlineCode(n)).join(", ") : "none"}`,
      "",
      "System prompt:",
      "",
      codeBlock(s.systemPrompt, "markdown"),
      "",
    );
  }

  out.push("## Guardrails", "");
  out.push(
    renderTable(
      ["Guardrail", "Value"],
      [
        ["Approval mode", g.approvalMode],
        ["Max turns", g.maxTurns],
        ["Max output tokens / turn", g.maxOutputTokensPerTurn],
        ["Max cost (USD)", g.maxCostUsd ?? "unlimited"],
        ["Blocked commands", g.blockedCommands.map((x) => inlineCode(x)).join(", ") || "none"],
        ["Allowed paths", g.allowedPaths.map((x) => inlineCode(x)).join(", ") || "none"],
        ["Redacted env vars", g.redactEnv.map((x) => inlineCode(x)).join(", ") || "none"],
      ],
    ),
    "",
  );

  out.push("## Context strategy", "");
  out.push(
    `- Prompt caching: ${c.caching ? "on (system prompt + tools cached; stable tool order)" : "off"}`,
    `- Compaction: ${c.compaction ? "on (server-side compaction for long sessions)" : "off"}`,
    `- Context editing: ${c.contextEditing ? "on (old tool results are cleared)" : "off"}`,
    `- Memory tool: ${c.memory ? "on" : "off"}`,
    "",
  );

  out.push("## Environment", "");
  if (spec.env.length === 0) out.push("_No environment variables._", "");
  else {
    out.push(
      renderTable(
        ["Name", "Description", "Required", "Secret", "Default"],
        spec.env.map((e) => [inlineCode(e.name), e.description, yesNo(e.required), yesNo(e.secret), e.default !== undefined && !e.secret ? inlineCode(e.default) : ""]),
      ),
      "",
    );
  }

  out.push(`## Evals (${spec.evals.length})`, "");
  if (spec.evals.length === 0) out.push("_No eval cases._", "");
  else {
    out.push(
      renderTable(
        ["Id", "Input", "Expectations", "Tags"],
        spec.evals.map((e) => [inlineCode(e.id), e.input, summarizeExpect(e.expect), (e.tags ?? []).join(", ")]),
      ),
      "",
    );
  }

  out.push("## Planner notes", "");
  const notes = spec.provenance.notes ?? [];
  if (notes.length === 0) out.push("_None._", "");
  else out.push(...notes.map((n) => `- ${n.trim().replace(/\r?\n/g, "\n  ")}`), "");

  return out.join("\n").replace(/\n+$/, "\n");
}

// ---------------------------------------------------------------------------

export function generateCommon(spec: HarnessSpec, opts: GenerateOptions): GeneratedFile[] {
  return [
    { path: "README.md", content: renderReadme(spec, opts).replace(/\n+$/, "\n") },
    { path: "evals.json", content: JSON.stringify(spec.evals, null, 2) + "\n" },
    { path: ".env.example", content: renderEnvExample(spec) },
    { path: "harness.md", content: renderHarnessDoc(spec, opts) },
    // Keeps list_files / search (runtime and generated targets) and the scanner out of the generated harness.
    { path: GENERATED_MARKER, content: GENERATED_MARKER_CONTENT },
  ];
}
