const ENV_NAME = /^[A-Za-z_][A-Za-z0-9_]*$/;

function envValue(v: string): string {
  if (v === "") return "";
  if (/[\s#"'`$\\=]/.test(v)) return JSON.stringify(v);
  return v;
}

function renderEnvExample(spec: HarnessSpec): string {
  const out: string[] = [`# Environment for ${oneLine(spec.displayName)}. Copy to .env and fill in.`, "# Secrets are left empty on purpose: never commit real values.", ""];
  const seen = new Set<string>();
  for (const e of spec.env) {
    if (seen.has(e.name)) continue;
    seen.add(e.name);
    for (const line of e.description.split(/\r?\n/)) if (line.trim()) out.push(`# ${line.trim()}`);
    const flags = [e.required ? "required" : "optional", e.secret ? "secret" : null].filter(Boolean).join(", ");
    out.push(`# (${flags})`);
    if (!ENV_NAME.test(e.name)) {
      out.push(`# skipped: ${JSON.stringify(e.name)} is not a valid env var name`, "");
      continue;
    }
    out.push(`${e.name}=${e.secret ? "" : envValue(e.default ?? "")}`, "");
  }
  const extra = toolEnvRefs(spec.tools).filter((n) => !seen.has(n) && ENV_NAME.test(n));
  if (extra.length) {
    out.push("# Referenced by tools but not declared in decree.json env:");
    for (const n of extra) {
      const isSecret = spec.tools.some((t) => t.http?.auth?.env === n);
      out.push(`${n}=${isSecret ? "" : envValue(envDefault(spec, n) ?? "")}`);
    }
    out.push("");
  }
  return out.join("\n").replace(/\n+$/, "\n");
}

