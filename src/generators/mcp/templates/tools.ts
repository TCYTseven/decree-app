const IGNORED_DIRS = new Set(["node_modules", ".git", "dist", ".decree"]);
const MAX_WALK = 100_000;

/** Convert a glob (*, **, ?, [..], {a,b}) to an anchored RegExp over POSIX relative paths. */
export function globToRegExp(glob: string): RegExp {
  let re = "";
  let inGroup = 0;
  for (let i = 0; i < glob.length; i++) {
    const c = glob[i]!;
    if (c === "*") {
      if (glob[i + 1] === "*") {
        const atStart = i === 0 || glob[i - 1] === "/";
        const atEnd = i + 2 === glob.length || glob[i + 2] === "/";
        if (atStart && atEnd) {
          i += 2; // consume "**" and a trailing "/"
          re += i >= glob.length ? ".*" : "(?:.*/)?";
          continue;
        }
        i++;
        re += "[^/]*";
        continue;
      }
      re += "[^/]*";
    } else if (c === "?") {
      re += "[^/]";
    } else if (c === "[") {
      const end = glob.indexOf("]", i + 1);
      if (end === -1) {
        re += "\\[";
      } else {
        let cls = glob.slice(i + 1, end).replace(/\\/g, "\\\\");
        if (cls.startsWith("!")) cls = "^" + cls.slice(1);
        re += "[" + cls + "]";
        i = end;
      }
    } else if (c === "{") {
      inGroup++;
      re += "(?:";
    } else if (c === "}" && inGroup > 0) {
      inGroup--;
      re += ")";
    } else if (c === "," && inGroup > 0) {
      re += "|";
    } else if (c === "\\" && i + 1 < glob.length) {
      i++;
      re += glob[i]!.replace(/[.*+?^$()|[\]\\{}]/g, "\\$&");
    } else {
      re += c.replace(/[.*+?^$()|[\]\\{}/]/g, "\\$&");
    }
  }
  return new RegExp("^" + re + "$");
}

/** Walk files under dir (sorted, POSIX relative paths), skipping ignored dirs and symlinked dirs. */
function walk(dir: string): string[] {
  const out: string[] = [];
  const stack: string[] = [""];
  while (stack.length > 0 && out.length < MAX_WALK) {
    const rel = stack.pop()!;
    let entries: fs.Dirent[];
    try {
      entries = fs.readdirSync(path.join(dir, rel), { withFileTypes: true });
    } catch {
      continue;
    }
    entries.sort((a, b) => (a.name < b.name ? 1 : a.name > b.name ? -1 : 0));
    for (const e of entries) {
      const child = rel ? rel + "/" + e.name : e.name;
      if (e.isDirectory()) {
        if (!IGNORED_DIRS.has(e.name)) stack.push(child);
      } else if (e.isFile() || e.isSymbolicLink()) {
        out.push(child);
      }
    }
  }
  return out.sort();
}

function listFilesTool(tool: ToolBinding, input: Input): ToolResult {
  const root = walkRoot(tool);
  const pattern = asText(input.pattern).replace(/^\.\//, "") || "**/*";
  const re = globToRegExp(pattern);
  const matches: string[] = [];
  let total = 0;
  for (const rel of walk(root)) {
    if (!re.test(rel)) continue;
    if (!safeChild(root, path.join(root, rel))) continue;
    total++;
    if (matches.length < 500) matches.push(rel);
  }
  if (matches.length === 0) return result("no files match " + pattern);
  const more = total > matches.length ? "\n…[" + (total - matches.length) + " more files not shown]" : "";
  return result(matches.join("\n") + more);
}

const SEARCH_MAX_MATCHES = 200;
const SEARCH_MAX_FILE_BYTES = 1_000_000;

function searchTool(tool: ToolBinding, input: Input): ToolResult {
  const root = walkRoot(tool);
  let re: RegExp;
  try {
    re = new RegExp(asText(input.query));
  } catch (err) {
    return result("Invalid regular expression: " + (err instanceof Error ? err.message : String(err)), true);
  }
  const glob = asText(input.glob).replace(/^\.\//, "");
  // Like ripgrep's -g: a glob without "/" matches the file name at any depth.
  const globRe = glob ? globToRegExp(glob.includes("/") ? glob : "**/" + glob) : null;
  const matches: string[] = [];
  let truncated = false;
  outer: for (const rel of walk(root)) {
    if (globRe && !globRe.test(rel)) continue;
    const abs = path.join(root, rel);
    if (!safeChild(root, abs)) continue;
    let buf: Buffer;
    try {
      const st = fs.statSync(abs);
      if (!st.isFile() || st.size > SEARCH_MAX_FILE_BYTES) continue;
      buf = fs.readFileSync(abs);
    } catch {
      continue;
    }
    if (buf.subarray(0, 8000).includes(0)) continue; // binary
    const lines = buf.toString("utf8").split(/\r?\n/);
    for (let i = 0; i < lines.length; i++) {
      re.lastIndex = 0;
      if (!re.test(lines[i]!)) continue;
      if (matches.length >= SEARCH_MAX_MATCHES) {
        truncated = true;
        break outer;
      }
      const line = lines[i]!.length > 500 ? lines[i]!.slice(0, 500) + "…" : lines[i]!;
      matches.push(rel + ":" + (i + 1) + ": " + line);
    }
  }
  if (matches.length === 0) return result("no matches");
  return result(matches.join("\n") + (truncated ? "\n…[stopped at " + SEARCH_MAX_MATCHES + " matches]" : ""));
}
