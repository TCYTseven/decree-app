function readFileTool(tool: ToolBinding, input: Input): ToolResult {
  const abs = resolveSafe(tool, asText(input.path));
  const max = tool.fs?.maxBytes ?? 200_000;
  const stat = fs.statSync(abs);
  if (stat.isDirectory()) return result("Not a file (directory): " + display(tool, abs), true);
  const fd = fs.openSync(abs, "r");
  try {
    const buf = Buffer.alloc(Math.min(stat.size, max));
    const n = fs.readSync(fd, buf, 0, buf.length, 0);
    let text = buf.subarray(0, n).toString("utf8");
    if (stat.size > max) text += "\n…[truncated " + (stat.size - max) + " bytes]";
    return result(text);
  } finally {
    fs.closeSync(fd);
  }
}

function writeFileTool(tool: ToolBinding, input: Input): ToolResult {
  const abs = resolveSafe(tool, asText(input.path));
  const content = asText(input.content);
  fs.mkdirSync(path.dirname(abs), { recursive: true });
  fs.writeFileSync(abs, content, "utf8");
  return result("wrote " + Buffer.byteLength(content, "utf8") + " bytes to " + display(tool, abs));
}

