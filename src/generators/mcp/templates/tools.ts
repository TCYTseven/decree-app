export async function runTool(name: string, input: Input): Promise<ToolResult> {
  const tool = TOOLS[name];
  if (!tool) return result("Unknown tool: " + name, true);
  try {
    switch (tool.kind) {
      case "http":
        return await runHttp(tool, input);
      case "shell":
        return await runShell(tool, input);
      case "read_file":
        return readFileTool(tool, input);
      case "write_file":
        return writeFileTool(tool, input);
      case "list_files":
        return listFilesTool(tool, input);
      case "search":
        return searchTool(tool, input);
    }
  } catch (err) {
    return result("Error: " + (err instanceof Error ? err.message : String(err)), true);
  }
}

