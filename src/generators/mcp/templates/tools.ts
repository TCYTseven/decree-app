function within(parent: string, child: string): boolean {
  const rel = path.relative(parent, child);
  return rel === "" || (!rel.startsWith("..") && !path.isAbsolute(rel));
}

/** realpath of the path, or of its nearest existing ancestor joined with the rest. */
function realish(p: string): string {
  let cur = p;
  const rest: string[] = [];
  for (;;) {
    try {
      return path.join(fs.realpathSync(cur), ...rest.reverse());
    } catch {
      const parent = path.dirname(cur);
      if (parent === cur) return p;
      rest.push(path.basename(cur));
      cur = parent;
    }
  }
}

function fsRoot(tool: ToolBinding): string {
  return path.resolve(PROJECT_ROOT, tool.fs?.root ?? ".");
}

/** Resolve a user-supplied path against the tool's root; throw if it escapes or is not allowed. */
export function resolveSafe(tool: ToolBinding, p: string): string {
  const root = fsRoot(tool);
  const abs = path.resolve(root, p || ".");
  if (!within(root, abs) || !within(realish(root), realish(abs))) {
    throw new Error("Path escapes the allowed root: " + p);
  }
  if (!isAllowed(abs)) throw new Error("Path is outside guardrails.allowedPaths: " + p);
  return abs;
}

/** Root of a walking tool (list_files/search): must stay inside the project; entries are filtered individually. */
function walkRoot(tool: ToolBinding): string {
  const root = fsRoot(tool);
  if (!within(PROJECT_ROOT, root) || !within(realish(PROJECT_ROOT), realish(root))) {
    throw new Error("Tool root escapes the project root: " + (tool.fs?.root ?? "."));
  }
  return root;
}

function isAllowed(abs: string): boolean {
  const real = realish(abs);
  return GUARDRAILS.allowedPaths.some((a) => {
    const allowed = path.resolve(PROJECT_ROOT, a);
    return within(allowed, abs) && within(realish(allowed), real);
  });
}

/** For entries found by walking: no symlink may lead outside the root or the allowed paths. */
function safeChild(root: string, abs: string): boolean {
  return within(realish(root), realish(abs)) && isAllowed(abs);
}

function display(tool: ToolBinding, abs: string): string {
  return path.relative(fsRoot(tool), abs).split(path.sep).join("/") || ".";
}

