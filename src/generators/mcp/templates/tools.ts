/** The binding data the runtime needs for one tool (no descriptions / schemas). */
function binding(t: ToolSpec): Record<string, unknown> {
  const b: Record<string, unknown> = { kind: t.kind };
  if (t.kind === "http" && t.http) {
    const h = t.http;
    const http: Record<string, unknown> = { method: h.method, baseUrlEnv: h.baseUrlEnv, path: h.path };
    if (h.defaultBaseUrl !== undefined) http.defaultBaseUrl = h.defaultBaseUrl;
    if (h.queryParams?.length) http.queryParams = h.queryParams;
    if (h.headerParams?.length) http.headerParams = h.headerParams;
    if (h.bodyParam !== undefined) http.bodyParam = h.bodyParam;
    if (h.auth) {
      const a: Record<string, unknown> = { type: h.auth.type };
      if (h.auth.env !== undefined) a.env = h.auth.env;
      if (h.auth.header !== undefined) a.header = h.auth.header;
      http.auth = a;
    }
    b.http = http;
  }
  if (t.kind === "shell" && t.shell) {
    const s: Record<string, unknown> = { command: t.shell.command };
    if (t.shell.cwd !== undefined) s.cwd = t.shell.cwd;
    if (t.shell.timeoutMs !== undefined) s.timeoutMs = t.shell.timeoutMs;
    const props = t.inputSchema?.properties ?? {};
    const allowFlags = Object.keys(props).filter((k) => (props[k] as Record<string, unknown> | undefined)?.["x-allow-flags"] === true);
    if (allowFlags.length) s.allowFlags = allowFlags;
    b.shell = s;
  }
  if (["read_file", "write_file", "list_files", "search"].includes(t.kind)) {
    const f: Record<string, unknown> = { root: t.fs?.root ?? "." };
    if (t.fs?.maxBytes !== undefined) f.maxBytes = t.fs.maxBytes;
    b.fs = f;
  }
  return b;
}

function indentJson(value: unknown, indent: string): string {
  return JSON.stringify(value, null, 2)
    .replace(/\u2028/g, "\\u2028")
    .replace(/\u2029/g, "\\u2029")
    .split("\n")
    .join(`\n${indent}`);
}

